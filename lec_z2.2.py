print("Программа вывода геометрической прогрессии")

a = float(input("Введите первый член прогрессии (b1): "))
b = float(input("Введите знаменатель прогрессии (q): "))
n = int(input("Введите количество членов прогрессии (n): "))

p = [0] * n

p[0] = a    
for i in range(1, n):
    p[i] = p[i-1] * b
print("\nГеометрическая прогрессия:")
for i in range(n):
    print(f"Член №{i+1}: {p[i]:.2f}")
